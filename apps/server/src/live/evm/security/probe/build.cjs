// Rebuilds probe/bytecode.ts from RoundTripProbe.sol. solc is not a project
// dependency, so run it from a scratch directory that has it installed:
//   cd "$(mktemp -d)" && npm i solc@0.8.26 && node <repo>/apps/server/src/live/evm/security/probe/build.cjs
// Settings: solc 0.8.26, via-IR, optimizer 200 runs, EVM paris (no PUSH0, runs on
// every supported chain), no metadata hash.
const fs = require('node:fs');
const path = require('node:path');
const { createRequire } = require('node:module');

const solc = createRequire(path.join(process.cwd(), 'noop.js'))('solc');
const source = fs.readFileSync(path.join(__dirname, 'RoundTripProbe.sol'), 'utf8');
const input = {
  language: 'Solidity',
  sources: { 'RoundTripProbe.sol': { content: source } },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    evmVersion: 'paris',
    viaIR: true,
    metadata: { bytecodeHash: 'none', appendCBOR: false },
    outputSelection: { '*': { '*': ['evm.deployedBytecode.object'] } },
  },
};
const out = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (out.errors ?? []).filter((e) => e.severity === 'error');
if (errors.length) {
  for (const e of errors) console.error(e.formattedMessage);
  process.exit(1);
}
const code = (name) => `0x${out.contracts['RoundTripProbe.sol'][name].evm.deployedBytecode.object}`;
const ts = `// Generated by build.cjs from RoundTripProbe.sol (solc ${solc.version()}, via-IR,
// optimizer 200, EVM paris). Do not edit by hand.

export const ROUND_TRIP_PROBE_RUNTIME = '${code('RoundTripProbe')}' as const;

export const CODE_SIZE_READER_RUNTIME = '${code('CodeSizeReader')}' as const;
`;
fs.writeFileSync(path.join(__dirname, 'bytecode.ts'), ts);
console.log(`wrote bytecode.ts (solc ${solc.version()})`);

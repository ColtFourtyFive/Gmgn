import type { AppContext } from '../src/context';
import { simOf } from '../src/sim/behaviors/fate';
import { Engine } from '../src/sim/engine';
import { MarketSim } from '../src/sim/market';
import { World } from '../src/sim/world';
import { serialize } from 'node:v8';
const endAt = Date.now();
const world = new World('trenchscope', endAt);
const engine = new Engine(world);
const market = new MarketSim({ world, engine } as unknown as AppContext);
market.install(); market.seedPopulation();
engine.warmup(Number(process.argv[2] ?? 120) * 60000, 1000, endAt);
let trades = 0, candles = 0, buckets = 0, makers = 0, holders = 0, traders = 0, hl = 0, positions = 0;
const byRes: Record<string, number> = {};
for (const t of world.tokens.values()) { trades += t.trades.length; for (const [r, c] of Object.entries(t.candles)) { candles += c.length; byRes[r] = (byRes[r] ?? 0) + c.length; } buckets += t.buckets.length; for (const b of t.buckets) makers += b.makers.size; holders += t.holders.size; traders += t.traders.size; hl += simOf(t).holderList.length; }
for (const w of world.wallets.values()) positions += w.positions.size;
console.log({ tokens: world.tokens.size, trades, candles, byRes, buckets, makers, holders, traders, hl, positions, queue: (market as any).scheduler.size });
global.gc?.();
console.log('heap MB', (process.memoryUsage().heapUsed / 2**20).toFixed(0));
const t0 = performance.now(); const snap = serialize({ world: world.serialize(), market: market.serialize() }); console.log('snapshot MB', (snap.length / 2**20).toFixed(1), 'in', (performance.now() - t0).toFixed(0), 'ms');
for (const t of world.tokens.values()) for (const tr of t.trades) tr.txHash.charCodeAt(1);
global.gc?.();
console.log('heap MB after flattening tx hashes', (process.memoryUsage().heapUsed / 2**20).toFixed(0));
for (const w of world.wallets.values()) w.address.charCodeAt(1);
for (const t of world.tokens.values()) t.address.charCodeAt(1);
global.gc?.();
console.log('heap MB after flattening addresses', (process.memoryUsage().heapUsed / 2**20).toFixed(0));
